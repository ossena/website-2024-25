let ripeti = 1000;
let i = 0;


//stampa la variabile ripeti per 5 volte 
while (i < ripeti) {
    console.log(ripeti);
    i++;
}

//crea conto alla rovesca #1
while (i < ripeti) {
    console.log(ripeti);
    ripeti--;
}

//conto alla rovesca #2
while (i < ripeti) {
    console.log(ripeti - i);
    i++;
}
